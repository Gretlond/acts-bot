def main():
    init_db()
    objects = get_all_objects()
    if not objects:
        print("⚠️ В базе нет объектов. Запустите seed_object_only.py.")
        return

    cats = {c["name"]: c["id"] for c in get_all_material_categories()}
    if not cats:
        print("⚠️ Категории не созданы. Запустите seed_material_categories.py.")
        return

    total_added = 0
    for obj in objects:
        existing = {m["name"] for m in get_materials_for_object(obj["id"])}
        added = 0
        for name, qdoc, work_types, cat_name in MATERIALS:
            if name in existing:
                continue
            cat_id = cats.get(cat_name)
            new_id = add_material(
                name=name,
                quality_doc=qdoc,
                object_id=obj["id"],
                work_types=work_types,
                category_id=cat_id,
            )
            added += 1
        total_added += added
        print(f"🏗 {obj['name'][:50]}…  →  добавлено {added} материалов")

    print(f"\n✅ Всего добавлено: {total_added}")


if __name__ == "__main__":
    main()
