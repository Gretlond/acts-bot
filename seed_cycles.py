def seed():
    print("🔧 Инициализация БД...")
    init_db()

    print("🗑  Удаляю старые дефолтные циклы (личные циклы мастеров сохраняются)...")
    clear_default_cycles()

    for cyc in CYCLES:
        cycle_id = add_cycle(cyc["name"], cyc["description"],
                             is_default=1, owner_tg_id=None)
        for i, (wt, tmpl, sect, sheets, mats) in enumerate(cyc["items"], start=1):
            add_cycle_item(cycle_id, i, wt, tmpl, sect, sheets, mats)
        print(f"  ✅ {cyc['name']} — {len(cyc['items'])} работ (id={cycle_id})")

    print("\n📊 Итог:")
    for c in get_all_cycles():
        items = get_cycle_items(c["id"])
        owner = "(личный)" if c.get("owner_tg_id") else "(дефолт)"
        print(f"  [{c['id']}] {owner} {c['name']} — {len(items)} работ")

    print("\n✅ seed_cycles.py выполнен.")


if __name__ == "__main__":
    seed()